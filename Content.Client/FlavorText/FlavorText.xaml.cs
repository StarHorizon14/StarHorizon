using Content.Shared._Horizon.FlavorText;
using Content.Shared.CCVar; // Horizon
using Robust.Shared.Configuration; // Horizon
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.FlavorText
{
    [GenerateTypedNameReferences]
    public sealed partial class FlavorText : Control
    {
        [Dependency] private readonly IConfigurationManager _cfg = default!; // Horizon

        public Action<string>? OnFlavorTextChanged;

        // Horizon start
        public Action<int>? OnErpStatChanged;
        public Action<string>? OnOOCFlavorTextChanged;
        public Action<string>? OnERPFlavorTextChanged;
        // Horizon end

        public FlavorText()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            var loc = IoCManager.Resolve<ILocalizationManager>();
            CFlavorTextInput.Placeholder = new Rope.Leaf(loc.GetString("flavor-text-placeholder"));
            CFlavorTextInput.OnTextChanged += _ => FlavorTextChanged();

            // Horizon start
            ERPStatusButton.OnItemSelected += args => OnErpStatChanged?.Invoke(args.Id);

            OOCFlavorTextInput.Placeholder = new Rope.Leaf(loc.GetString("ooc-flavor-text-placeholder"));
            OOCFlavorTextInput.OnTextChanged += args => OnOOCFlavorTextChanged?.Invoke(Rope.Collapse(OOCFlavorTextInput.TextRope).Trim());

            ERPFlavorTextInput.Placeholder = new Rope.Leaf(loc.GetString("erp-flavor-text-placeholder"));
            ERPFlavorTextInput.OnTextChanged += args => OnERPFlavorTextChanged?.Invoke(Rope.Collapse(ERPFlavorTextInput.TextRope).Trim());

            UpdateFlavorTextCounter();
            // Horizon end
        }

        public void FlavorTextChanged()
        {
            UpdateFlavorTextCounter(); // Horizon
            OnFlavorTextChanged?.Invoke(Rope.Collapse(CFlavorTextInput.TextRope).Trim());
        }

        /// <summary>
        /// Horizon: show how many characters are left before the description gets cut off on save.
        /// </summary>
        public void UpdateFlavorTextCounter()
        {
            var max = _cfg.GetCVar(CCVars.MaxFlavorTextLength);
            var length = Rope.Collapse(CFlavorTextInput.TextRope).Trim().Length;
            var left = max - length;

            CFlavorTextCounter.Text = left >= 0
                ? Loc.GetString("flavor-text-counter", ("left", left), ("max", max))
                : Loc.GetString("flavor-text-counter-over", ("over", -left), ("max", max));
            CFlavorTextCounter.FontColorOverride = left >= 0 ? Color.Gray : Color.Red;
        }
    }
}
