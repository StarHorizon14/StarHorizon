using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._Horizon._Fractions.AnCo.WeaponCaseHack;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Horizon._Fractions.AnCo.WeaponCaseHack;

[GenerateTypedNameReferences]
public sealed partial class AnCoWeaponCaseHackWindow : FancyWindow
{
    public event Action<AnCoHackDir, int>? OnChoose;

    [Dependency] private readonly IGameTiming _timing = default!;

    private const double WarningSeconds = 10;

    // Мигающий блок-курсор после условия (на сайте - console-cursor у заголовка): шаг ~0.55 с.
    private const float CursorPeriod = 0.55f;

    private int _nodeIndex;
    private TimeSpan? _deadline;
    private string _ruleText = string.Empty;
    private bool _cursorOn = true;
    private float _cursorTime;

    public AnCoWeaponCaseHackWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ApplyTheme();

        LeftButton.OnPressed += _ => OnChoose?.Invoke(AnCoHackDir.Left, _nodeIndex);
        UpButton.OnPressed += _ => OnChoose?.Invoke(AnCoHackDir.Up, _nodeIndex);
        RightButton.OnPressed += _ => OnChoose?.Invoke(AnCoHackDir.Right, _nodeIndex);
    }

    private void ApplyTheme()
    {
        var mono14 = AnCoConsoleTheme.Mono(14);
        var mono16 = AnCoConsoleTheme.Mono(16);

        // Чёрный фон окна и плоские рамки панелей (как .card на сайте).
        BackgroundPanel.PanelOverride = AnCoConsoleTheme.Box(AnCoConsoleTheme.Background, AnCoConsoleTheme.Border);
        StatusPanel.PanelOverride = AnCoConsoleTheme.Box(AnCoConsoleTheme.Panel, AnCoConsoleTheme.Border);
        MapPanel.PanelOverride = AnCoConsoleTheme.Box(AnCoConsoleTheme.MapBackground, AnCoConsoleTheme.Border);
        RulePanel.PanelOverride = AnCoConsoleTheme.Box(AnCoConsoleTheme.Panel, AnCoConsoleTheme.Border);

        // Заголовок окна: терминальный шрифт и цвет заголовков сайта.
        StyleTitle(this, mono16);

        // Подписи - приглушённый красный, значения - акцентный, заголовки - яркий красный.
        foreach (var label in new[] { AttemptsTitle, TimerTitle })
        {
            label.FontOverride = mono14;
            label.FontColorOverride = AnCoConsoleTheme.Text;
        }

        foreach (var label in new[] { AttemptsLabel, TimerLabel })
        {
            label.FontOverride = mono16;
            label.FontColorOverride = AnCoConsoleTheme.Accent;
        }

        ConditionHeader.FontOverride = mono14;
        ConditionHeader.FontColorOverride = AnCoConsoleTheme.Heading;

        foreach (var label in new[] { SerialLeftLabel, SerialRightLabel })
        {
            label.FontOverride = mono14;
            label.FontColorOverride = AnCoConsoleTheme.Accent;
        }
    }

    /// <summary>
    /// Метка заголовка принадлежит <see cref="FancyWindow"/> и недоступна наследникам, поэтому ищем её по стилевому классу.
    /// </summary>
    private static void StyleTitle(Control root, Font font)
    {
        foreach (var child in root.Children)
        {
            if (child is Label label && label.HasStyleClass("FancyWindowTitle"))
            {
                label.FontOverride = font;
                label.FontColorOverride = AnCoConsoleTheme.Heading;
                return;
            }

            StyleTitle(child, font);
        }
    }

    public void UpdateState(AnCoHackBoundUserInterfaceState state)
    {
        _nodeIndex = state.NodeIndex;
        _deadline = state.Deadline;
        UpdateTimer();

        AttemptsLabel.Text = Loc.GetString("anco-weapon-case-hack-attempts",
            ("attempts", state.Attempts), ("max", state.MaxAttempts));
        _ruleText = Loc.GetString(state.RuleLocId);
        UpdateRule();

        // Серийник подписан направлением, в котором лежит его дорожка.
        SerialLeftLabel.Text = $"{Arrow(state.CurrentLeftExit)} {state.SerialB}";
        SerialRightLabel.Text = $"{Arrow(state.CurrentRightExit)} {state.SerialC}";

        // Кнопка направления без выхода неактивна.
        LeftButton.Disabled = !HasExit(state, AnCoHackDir.Left);
        UpButton.Disabled = !HasExit(state, AnCoHackDir.Up);
        RightButton.Disabled = !HasExit(state, AnCoHackDir.Right);

        Map.Update(state);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateTimer();

        _cursorTime += args.DeltaSeconds;
        if (_cursorTime >= CursorPeriod)
        {
            _cursorTime = 0;
            _cursorOn = !_cursorOn;
            UpdateRule();
        }
    }

    /// <summary>
    /// Условие белым моно-шрифтом с мигающим блоком в конце. Блок всегда занимает место, чтобы текст не прыгал.
    /// </summary>
    private void UpdateRule()
    {
        var cursorColor = _cursorOn ? AnCoConsoleTheme.Accent : AnCoConsoleTheme.Background;
        RuleLabel.SetMarkupPermissive(
            $"[font=\"Monospace\" size=14][color={AnCoConsoleTheme.Highlight.ToHex()}]{FormattedMessage.EscapeText(_ruleText)}[/color]" +
            $" [color={cursorColor.ToHex()}]█[/color][/font]");
    }

    private void UpdateTimer()
    {
        if (_deadline is not { } deadline)
        {
            // Таймер стартует с первого ответа.
            TimerLabel.Text = Loc.GetString("anco-weapon-case-hack-timer-idle");
            TimerLabel.FontColorOverride = AnCoConsoleTheme.Accent;
            return;
        }

        var left = Math.Max(0, (deadline - _timing.CurTime).TotalSeconds);
        TimerLabel.Text = Loc.GetString("anco-weapon-case-hack-timer", ("seconds", (int) Math.Ceiling(left)));
        TimerLabel.FontColorOverride = left <= WarningSeconds ? AnCoConsoleTheme.Danger : AnCoConsoleTheme.Accent;
    }

    private static bool HasExit(AnCoHackBoundUserInterfaceState state, AnCoHackDir dir)
    {
        return state.CurrentLeftExit == dir || state.CurrentRightExit == dir;
    }

    private static string Arrow(AnCoHackDir dir)
    {
        return dir switch
        {
            AnCoHackDir.Left => Loc.GetString("anco-weapon-case-hack-dir-left"),
            AnCoHackDir.Up => Loc.GetString("anco-weapon-case-hack-dir-up"),
            _ => Loc.GetString("anco-weapon-case-hack-dir-right"),
        };
    }
}
