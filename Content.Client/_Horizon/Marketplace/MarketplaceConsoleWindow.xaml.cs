[GenerateTypedNameReferences]
public sealed partial class MarketplaceConsoleWindow : FancyWindow
{
    private enum SortMode
    {
        Newest,
        PriceAscending,
        PriceDescending,
        Name,
        Count,
    }

    private MarketplaceTheme _theme = MarketplaceTheme.Sector;
    private string MutedColor => _theme.Muted;
    private string PriceColor => _theme.Price;
    private string AccentColor => _theme.Accent;

    public event Action<int, int>? OnList;
    public event Action<int, int, int>? OnBuy;
    public event Action<int>? OnWithdraw;
    public event Action? OnEject;
    public event Action<string, string, int, int>? OnCreateRequest;
    public event Action<int>? OnCancelRequest;
    public event Action<int, int>? OnMakeOffer;
    public event Action<int>? OnAcceptOffer;
    public event Action<int>? OnRejectOffer;
    public event Action<int>? OnWithdrawOffer;

    private MarketplaceConsoleState? _state;
    private SortMode _sort = SortMode.Newest;

    private MarketplaceItemIcon _slotIcon = new(128);
    private NetEntity? _slotEntity;
    private int _slotCount;
    private int _sellAmount = 1;

    /// <summary>
    /// Amounts picked on listing cards, kept across refreshes.
    /// </summary>
    private readonly Dictionary<int, int> _buyAmounts = new();

    /// <summary>
    /// Amounts picked for offers on request cards, kept across refreshes.
    /// </summary>
    private readonly Dictionary<int, int> _offerAmounts = new();

    private MarketplaceRequestForm? _requestForm;

    public MarketplaceConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        Tabs.SetTabTitle(0, Loc.GetString("marketplace-tab-market"));
        Tabs.SetTabTitle(1, Loc.GetString("marketplace-tab-requests"));
        Tabs.SetTabTitle(2, Loc.GetString("marketplace-tab-sell"));
        Tabs.SetTabTitle(3, Loc.GetString("marketplace-tab-mine"));

        ApplyTheme(MarketplaceTheme.Sector);

        SortButton.AddItem(Loc.GetString("marketplace-sort-newest"), (int) SortMode.Newest);
        SortButton.AddItem(Loc.GetString("marketplace-sort-price-asc"), (int) SortMode.PriceAscending);
        SortButton.AddItem(Loc.GetString("marketplace-sort-price-desc"), (int) SortMode.PriceDescending);
        SortButton.AddItem(Loc.GetString("marketplace-sort-name"), (int) SortMode.Name);
        SortButton.AddItem(Loc.GetString("marketplace-sort-count"), (int) SortMode.Count);
        SortButton.OnItemSelected += args =>
        {
            SortButton.SelectId(args.Id);
            _sort = (SortMode) args.Id;
            RebuildListings();
        };

        SearchBar.OnTextChanged += _ => RebuildListings();

        PriceEdit.IsValid = text => text.Length == 0 || text.Length <= 9 && text.All(char.IsDigit);
        PriceEdit.OnTextChanged += _ => UpdateSellSummary();

        AmountAllButton.OnPressed += _ =>
        {
            _sellAmount = Math.Max(1, _slotCount);
            RebuildAmountSpinBox();
            UpdateSellSummary();
        };

        EjectButton.OnPressed += _ => OnEject?.Invoke();
        ListButton.OnPressed += _ =>
        {
            if (TryGetPrice(out var price))
                OnList?.Invoke(_sellAmount, price);
        };

        RequestSearch.OnTextChanged += _ => RebuildRequests();
        OnlyMyRequests.OnToggled += _ => RebuildRequests();

    }

    /// <summary>
    /// Recolours the window, e.g. red for the black market. Call before the first state arrives.
    /// </summary>
    public void ApplyTheme(MarketplaceTheme theme)
    {
        _theme = theme;

        Title = Loc.GetString(theme.WindowTitleKey);
        HeaderTitle.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString(theme.HeaderTitleKey)));
        HeaderPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = theme.HeaderBackground,
            BorderColor = theme.HeaderBorder,
            BorderThickness = new Thickness(0, 0, 0, 2),
            ContentMarginLeftOverride = 12,
            ContentMarginRightOverride = 12,
            ContentMarginTopOverride = 8,
            ContentMarginBottomOverride = 8,
        };

        foreach (var chip in new[] { BalanceChip, TaxChip, CountChip })
        {
            chip.PanelOverride = MakeChipStyle(theme.ChipBorder);
        }

        PendingChip.PanelOverride = MakeChipStyle(theme.OwnBorder);

        var panelStyle = new StyleBoxFlat
        {
            BackgroundColor = theme.CardBackground,
            BorderColor = theme.CardBorder,
            BorderThickness = new Thickness(1),
        };
        SlotPanel.PanelOverride = panelStyle;
        SellPanel.PanelOverride = panelStyle;
        CreateRequestPanel.PanelOverride = panelStyle;

        // The form takes its colours on creation, so rebuild it for the new theme.
        RequestFormBox.RemoveAllChildren();
        _requestForm = new MarketplaceRequestForm(theme);
        _requestForm.OnCreate += (title, description, quantity, reward) =>
            OnCreateRequest?.Invoke(title, description, quantity, reward);
        RequestFormBox.AddChild(_requestForm);
        SummaryPanel.PanelOverride = theme.MakeInset();
        SummaryDivider.PanelOverride = new StyleBoxFlat { BackgroundColor = theme.CardBorder };

        SlotIconBox.RemoveAllChildren();
        _slotIcon = new MarketplaceItemIcon(128, theme);
        SlotIconBox.AddChild(_slotIcon);


        if (_state != null)
            UpdateState(_state);
    }

    private StyleBoxFlat MakeChipStyle(Color border)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = _theme.ChipBackground,
            BorderColor = border,
            BorderThickness = new Thickness(1),
        };
    }

    public void UpdateState(MarketplaceConsoleState state)
    {
        _state = state;

        HeaderTerminal.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("marketplace-header-terminal",
            ("grid", FormattedMessage.EscapeText(state.GridName)),
            ("mutedColor", MutedColor),
            ("accentColor", AccentColor))));

        BalanceLabel.SetMessage(FormattedMessage.FromMarkupPermissive(state.HasAccount
            ? Loc.GetString("marketplace-stat-balance",
                ("balance", BankSystemExtensions.ToSpesoString(state.Balance)),
                ("mutedColor", MutedColor),
                ("priceColor", PriceColor))
            : Loc.GetString("marketplace-stat-no-account", ("mutedColor", MutedColor))));

        TaxLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("marketplace-stat-tax",
            ("tax", GetTaxPercent()),
            ("mutedColor", MutedColor))));

        CountLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("marketplace-stat-listings",
            ("count", state.Listings.Count),
            ("mutedColor", MutedColor))));

        PendingChip.Visible = state.PendingPayout > 0;
        PendingLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("marketplace-stat-pending",
            ("amount", BankSystemExtensions.ToSpesoString(state.PendingPayout)),
            ("mutedColor", MutedColor))));

        TaxRowLabel.Text = Loc.GetString("marketplace-sell-tax", ("tax", GetTaxPercent()));

        RebuildListings();
        RebuildOwnListings();
        UpdateSlot();
        RebuildRequests();
        RebuildMyOffers();
        UpdateRequestForm();
    }

    private int GetTaxPercent()
    {
        return _state == null ? 0 : (int) MathF.Round(_state.TaxRate * 100f);
    }

    #region Market

    private void RebuildListings()
    {
        ListingsGrid.RemoveAllChildren();
        if (_state == null)
            return;

        var search = SearchBar.Text.Trim();
        IEnumerable<MarketplaceListingData> listings = _state.Listings;

        if (search.Length > 0)
        {
            listings = listings.Where(l =>
                l.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                || l.SellerName.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                || l.SellerIdName.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                || l.GridName.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                || int.TryParse(search.TrimStart('#'), out var id) && l.Id == id);
        }

        listings = _sort switch
        {
            SortMode.PriceAscending => listings.OrderBy(l => l.UnitPrice).ThenBy(l => l.Name),
            SortMode.PriceDescending => listings.OrderByDescending(l => l.UnitPrice).ThenBy(l => l.Name),
            SortMode.Name => listings.OrderBy(l => l.Name.ToLowerInvariant()).ThenBy(l => l.UnitPrice),
            SortMode.Count => listings.OrderByDescending(l => l.Count).ThenBy(l => l.UnitPrice),
            _ => listings.OrderByDescending(l => l.ListedAt).ThenByDescending(l => l.Id),
        };

        var any = false;
        foreach (var listing in listings)
        {
            ListingsGrid.AddChild(CreateCard(listing));
            any = true;
        }

        ListingsEmpty.Visible = !any;
        ListingsEmpty.Text = Loc.GetString(_state.Listings.Count == 0 ? "marketplace-empty" : "marketplace-empty-search");
    }

    private void RebuildOwnListings()
    {
        OwnGrid.RemoveAllChildren();
        if (_state == null)
            return;

        var any = false;
        foreach (var listing in _state.Listings.Where(l => l.IsOwn).OrderByDescending(l => l.ListedAt))
        {
            OwnGrid.AddChild(CreateCard(listing));
            any = true;
        }

        OwnEmpty.Visible = !any;
    }

    private MarketplaceListingCard CreateCard(MarketplaceListingData listing)
    {
        var card = new MarketplaceListingCard(_theme,
            listing,
            _state?.Balance ?? 0,
            _state?.HasAccount ?? false,
            _buyAmounts.GetValueOrDefault(listing.Id, 1));
        card.OnAmountChanged += (id, amount) => _buyAmounts[id] = amount;
        card.OnBuy += (id, amount, price) => OnBuy?.Invoke(id, amount, price);
        card.OnWithdraw += id => OnWithdraw?.Invoke(id);
        return card;
    }

    #endregion

    #region Sell

    private void UpdateSlot()
    {
        if (_state == null)
            return;

        var changed = _slotEntity != _state.SlotEntity || _slotCount != _state.SlotCount;
        _slotEntity = _state.SlotEntity;
        _slotCount = _state.SlotCount;

        if (_state.SlotEntity == null)
        {
            _slotIcon.SetItem(null, null);
            SlotNameLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("marketplace-sell-slot-empty",
                ("mutedColor", MutedColor))));
            SlotCountLabel.Visible = false;
            SlotDenyLabel.Visible = false;
            EjectButton.Disabled = true;
        }
        else
        {
            _slotIcon.SetItem(_state.SlotEntity, null, _state.SlotStackable ? _state.SlotCount : null);
            SlotNameLabel.SetMessage(FormattedMessage.FromMarkupPermissive(
                $"[bold]{FormattedMessage.EscapeText(_state.SlotName ?? string.Empty)}[/bold]"));
            SlotCountLabel.Visible = true;
            SlotCountLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("marketplace-sell-available",
                ("count", _state.SlotCount),
                ("mutedColor", MutedColor))));
            SlotDenyLabel.Visible = _state.SlotDenyReason != null;
            SlotDenyLabel.SetMessage(FormattedMessage.FromMarkupPermissive(
                $"[color={_theme.Danger}]{FormattedMessage.EscapeText(_state.SlotDenyReason ?? string.Empty)}[/color]"));
            EjectButton.Disabled = false;
        }

        AmountRow.Visible = _state.SlotStackable;
        PriceLabel.Text = Loc.GetString(_state.SlotStackable ? "marketplace-sell-price-unit" : "marketplace-sell-price-single");

        // Only rebuild the spin box when the item changes, so typing into it isn't interrupted by unrelated updates.
        if (changed || AmountSpinBox.ChildCount == 0)
        {
            _sellAmount = Math.Max(1, _state.SlotCount);
            RebuildAmountSpinBox();
        }

        UpdateSellSummary();
    }

    private void RebuildAmountSpinBox()
    {
        AmountSpinBox.RemoveAllChildren();
        var spin = MarketplaceListingCard.CreateAmountSpinBox(Math.Max(1, _slotCount), _sellAmount, value =>
        {
            _sellAmount = value;
            UpdateSellSummary();
        });
        spin.HorizontalExpand = true;
        AmountSpinBox.AddChild(spin);
    }

    private bool TryGetPrice(out int price)
    {
        return int.TryParse(PriceEdit.Text, out price) && price > 0;
    }

    private void UpdateSellSummary()
    {
        if (_state == null)
            return;

        var amount = _state.SlotStackable ? _sellAmount : 1;
        var hasPrice = TryGetPrice(out var price);
        var total = hasPrice ? (long) price * amount : 0;
        var clampedTotal = (int) Math.Min(total, int.MaxValue);
        var tax = SharedMarketplaceSystem.GetTax(clampedTotal, _state.TaxRate);

        SumLabel.SetMessage(FormattedMessage.FromMarkupPermissive(
            $"[bold]{BankSystemExtensions.ToSpesoString(clampedTotal)}[/bold]"));
        TaxAmountLabel.SetMessage(FormattedMessage.FromMarkupPermissive(
            $"[color=#FF8A6B]-{BankSystemExtensions.ToSpesoString(tax)}[/color]"));
        ReceiveLabel.SetMessage(FormattedMessage.FromMarkupPermissive(
            $"[bold][color={PriceColor}]{BankSystemExtensions.ToSpesoString(clampedTotal - tax)}[/color][/bold]"));

        // Show when the new listing will be merged into an existing one.
        MarketplaceListingData? mergeTarget = null;
        if (hasPrice && _state.SlotStackType != null)
        {
            mergeTarget = _state.Listings.FirstOrDefault(l =>
                l.IsOwn && l.StackType == _state.SlotStackType && l.UnitPrice == price);
        }

        MergeLabel.Visible = mergeTarget != null;
        if (mergeTarget != null)
        {
            MergeLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("marketplace-sell-merge",
                ("id", mergeTarget.Id),
                ("count", mergeTarget.Count),
                ("accentColor", AccentColor))));
        }

        var priceValid = hasPrice && price <= _state.MaxUnitPrice;
        ListButton.Disabled = _state.SlotEntity == null
                              || _state.SlotDenyReason != null
                              || !_state.HasAccount
                              || !priceValid;
    }

    #endregion

    #region Requests

    private void UpdateRequestForm()
    {
        if (_state == null || _requestForm == null)
            return;

        _requestForm.SetLimits(_state.TaxRate,
            _state.Balance,
            _state.HasAccount,
            _state.MaxUnitPrice,
            _state.Requests.Count(r => r.IsOwn) >= _state.MaxRequestsPerPlayer);
    }

    private void RebuildRequests()
    {
        RequestsList.RemoveAllChildren();
        if (_state == null)
            return;

        var search = RequestSearch.Text.Trim();
        IEnumerable<MarketplaceRequestData> requests = _state.Requests;

        if (OnlyMyRequests.Pressed)
            requests = requests.Where(r => r.IsOwn);

        if (search.Length > 0)
        {
            requests = requests.Where(r =>
                r.Title.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                || r.Description.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                || r.RequesterName.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                || r.GridName.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                || int.TryParse(search.TrimStart('#'), out var id) && r.Id == id);
        }

        // The viewer's own requests with offers waiting come first, then the newest.
        requests = requests
            .OrderByDescending(r => r.IsOwn && r.Offers.Count > 0)
            .ThenByDescending(r => r.CreatedAt)
            .ThenByDescending(r => r.Id);

        var slotName = _state.SlotEntity != null ? _state.SlotName : null;
        var slotCount = _state.SlotStackable ? _state.SlotCount : 0;

        var any = false;
        foreach (var request in requests)
        {
            var card = new MarketplaceRequestCard(_theme,
                request,
                slotName,
                slotCount,
                _state.SlotDenyReason,
                _offerAmounts.GetValueOrDefault(request.Id));
            card.OnCancel += id => OnCancelRequest?.Invoke(id);
            card.OnOffer += (id, amount) => OnMakeOffer?.Invoke(id, amount);
            card.OnAccept += id => OnAcceptOffer?.Invoke(id);
            card.OnReject += id => OnRejectOffer?.Invoke(id);
            card.OnOfferAmountChanged += (id, amount) => _offerAmounts[id] = amount;
            RequestsList.AddChild(card);
            any = true;
        }

        RequestsEmpty.Visible = !any;
        RequestsEmpty.Text = Loc.GetString(_state.Requests.Count == 0 ? "marketplace-request-empty" : "marketplace-empty-search");
    }

    private void RebuildMyOffers()
    {
        MyOffersList.RemoveAllChildren();
        if (_state == null)
            return;

        foreach (var offer in _state.MyOffers.OrderBy(o => o.Status).ThenByDescending(o => o.Id))
        {
            var row = MarketplaceRequestCard.CreateOfferRow(_theme, offer, showRequest: true);
            var button = new Button
            {
                Text = Loc.GetString(offer.Status == MarketplaceOfferStatus.Pending
                    ? "marketplace-offer-withdraw"
                    : "marketplace-offer-take-back"),
            };
            if (offer.Status == MarketplaceOfferStatus.Returned)
                button.AddStyleClass(StyleNano.StyleClassButtonColorGreen);

            button.OnPressed += _ => OnWithdrawOffer?.Invoke(offer.Id);
            row.Buttons.AddChild(button);
            MyOffersList.AddChild(row);
        }

        MyOffersEmpty.Visible = _state.MyOffers.Count == 0;
    }

    #endregion
}
