using Content.Client.UserInterface.Controls;
using Content.Shared._Horizon.SlimeAppearance;
using Content.Shared.Humanoid;
using Content.Shared.Humanoid.Markings;
using Content.Shared.Humanoid.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Horizon.SlimeAppearance;

/// <summary>
/// Appearance editor for slime people. Changes are only a draft until "Apply" is pressed.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SlimeAppearanceWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;

    public event Action<MarkingSet, Sex, Color, Color>? OnApply;

    private readonly ColorSelectorSliders _skinColorSelector;
    private MarkingSet _markings = new();
    private string _species = SharedHumanoidAppearanceSystem.DefaultSpecies;
    private Sex _sex = Sex.Unsexed;
    private Color _eyeColor = Color.Black;

    public SlimeAppearanceWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SkinColorContainer.AddChild(_skinColorSelector = new ColorSelectorSliders());
        _skinColorSelector.SelectorType = ColorSelectorSliders.ColorSelectorType.Hsv;
        _skinColorSelector.OnColorChanged += color =>
        {
            MarkingPickerWidget.SetSkinColor(color);
            MarkingPickerWidget.SetData(_markings, _species, _sex, color, _eyeColor);
        };

        EyeColorPickerWidget.OnEyeColorPicked += color =>
        {
            _eyeColor = color;
            MarkingPickerWidget.SetEyeColor(color);
        };

        MarkingPickerWidget.OnMarkingAdded += set => _markings = set;
        MarkingPickerWidget.OnMarkingRemoved += set => _markings = set;
        MarkingPickerWidget.OnMarkingColorChange += set => _markings = set;
        MarkingPickerWidget.OnMarkingRankChange += set => _markings = set;

        SexButton.OnItemSelected += args =>
        {
            SexButton.SelectId(args.Id);
            _sex = (Sex) args.Id;
            // Markings depend on the sex, refilter them
            MarkingPickerWidget.SetData(_markings, _species, _sex, _skinColorSelector.Color, _eyeColor);
        };

        HintLabel.Text = Loc.GetString("slime-appearance-window-hint");
        ApplyButton.OnPressed += _ => OnApply?.Invoke(_markings, _sex, _skinColorSelector.Color, _eyeColor);
    }

    public void UpdateState(SlimeAppearanceBoundUserInterfaceState state)
    {
        _markings = new MarkingSet(state.Markings);
        _species = state.Species;
        _sex = state.Sex;
        _eyeColor = state.EyeColor;

        UpdateSexButton();

        _skinColorSelector.Color = state.SkinColor;
        EyeColorPickerWidget.SetData(state.EyeColor);
        MarkingPickerWidget.SetData(_markings, state.Species, state.Sex, state.SkinColor, state.EyeColor);
    }

    /// <summary>
    /// Same sex list as the character editor, taken from the species
    /// </summary>
    private void UpdateSexButton()
    {
        SexButton.Clear();

        var sexes = _proto.TryIndex<SpeciesPrototype>(_species, out var species)
            ? species.Sexes
            : new List<Sex> { _sex };

        if (!sexes.Contains(_sex))
            sexes = new List<Sex>(sexes) { _sex };

        foreach (var sex in sexes)
        {
            SexButton.AddItem(Loc.GetString($"humanoid-profile-editor-sex-{sex.ToString().ToLower()}-text"), (int) sex);
        }

        SexButton.SelectId((int) _sex);
    }
}
