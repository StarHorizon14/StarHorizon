using Content.Client.UserInterface.Controls;
using Content.Shared._Horizon.Shipbreaking.Derelict;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Horizon.Shipbreaking.Derelict;

[GenerateTypedNameReferences]
public sealed partial class DerelictYardMenu : FancyWindow
{
    public event Action<string>? OnSelected;
    public event Action<string>? OnBuy;
    public event Action<NetEntity>? OnExtend;

    private DerelictYardState? _state;
    private string? _selected;
    private readonly List<(Label Label, DerelictLeaseEntry Entry)> _leaseLabels = new();
    private TimeSpan _stateTime;

    public DerelictYardMenu()
    {
        RobustXamlLoader.Load(this);

        BuyButton.OnPressed += _ =>
        {
            if (_selected != null)
                OnBuy?.Invoke(_selected);
        };
    }

    public void UpdateState(DerelictYardState state)
    {
        _state = state;
        _stateTime = IoCManager.Resolve<IGameTiming>().RealTime;
        BalanceLabel.Text = state.Balance is { } balance ? Loc.GetString("derelict-yard-money", ("amount", balance)) : "-";

        RankLabel.Text = state.NextRankAt is { } next
            ? Loc.GetString("derelict-yard-rank", ("rank", state.Rank), ("exp", state.Experience), ("next", next))
            : Loc.GetString("derelict-yard-rank-max", ("rank", state.Rank), ("exp", state.Experience));

        UpdateLeases(state);

        VesselList.RemoveAllChildren();
        foreach (var vessel in state.Vessels)
        {
            var id = vessel.Id;
            var button = new Button
            {
                Text = vessel.Locked
                    ? Loc.GetString("derelict-yard-row-locked", ("name", vessel.Name), ("price", vessel.Price), ("rank", vessel.MinRank))
                    : Loc.GetString("derelict-yard-row", ("name", vessel.Name), ("price", vessel.Price)),
                HorizontalExpand = true,
                ToggleMode = true,
                Pressed = id == _selected,
            };
            button.OnPressed += _ => Select(id);
            VesselList.AddChild(button);
        }

        if (_selected == null && state.Vessels.Count > 0)
            Select(state.Vessels[0].Id);
        else
            RefreshSelected();
    }

    private void Select(string id)
    {
        _selected = id;
        Preview.Clear();
        OnSelected?.Invoke(id);
        UpdateState(_state ?? new DerelictYardState());
    }

    private void RefreshSelected()
    {
        var vessel = _state?.Vessels.Find(v => v.Id == _selected);
        if (vessel == null)
        {
            NameLabel.Text = string.Empty;
            DescriptionLabel.SetMessage(string.Empty);
            PriceLabel.Text = string.Empty;
            BuyButton.Disabled = true;
            return;
        }

        NameLabel.Text = vessel.Name;
        DescriptionLabel.SetMessage(FormattedMessage.FromUnformatted(vessel.Description));
        PriceLabel.Text = Loc.GetString("derelict-yard-price", ("price", vessel.Price), ("minutes", (int) vessel.Lifetime.TotalMinutes));
        BuyButton.Disabled = vessel.Locked || _state?.Balance is not { } balance || balance < vessel.Price;
    }

    private void UpdateLeases(DerelictYardState state)
    {
        LeaseList.RemoveAllChildren();
        _leaseLabels.Clear();

        foreach (var lease in state.Leases)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            var label = new Label { HorizontalExpand = true };
            row.AddChild(label);

            var group = lease.Group;
            var button = new Button
            {
                Text = Loc.GetString("derelict-yard-extend", ("price", lease.ExtendPrice)),
                Disabled = !lease.CanExtend || state.Balance is not { } balance || balance < lease.ExtendPrice,
            };
            button.OnPressed += _ => OnExtend?.Invoke(group);
            row.AddChild(button);

            LeaseList.AddChild(row);
            _leaseLabels.Add((label, lease));
        }

        RefreshLeaseLabels();
    }

    private void RefreshLeaseLabels()
    {
        var passed = IoCManager.Resolve<IGameTiming>().RealTime - _stateTime;
        foreach (var (label, lease) in _leaseLabels)
        {
            var left = lease.Left - passed;
            if (left < TimeSpan.Zero)
                left = TimeSpan.Zero;

            label.Text = Loc.GetString("derelict-yard-lease-row",
                ("name", lease.Name),
                ("time", $"{(int) left.TotalMinutes:00}:{left.Seconds:00}"),
                ("share", (int) MathF.Round(lease.Share * 100f)));
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        RefreshLeaseLabels();
    }

    public void SetPreview(DerelictPreviewMessage message)
    {
        if (message.Id == _selected)
            Preview.SetPreview(message.Tiles, message.Colors);
    }
}
